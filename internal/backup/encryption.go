package backup

import (
	"bytes"
	"context"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/atikansari-ghr/BookmarksSync/internal/securefile"
	"golang.org/x/crypto/hkdf"
)

const (
	RecoveryKeySize      = 32
	encryptionChunkSize  = 1 << 20
	encryptionHeaderSize = 24
)

var encryptionMagic = [8]byte{'B', 'M', 'S', 'E', 'N', 'C', '0', '1'}

const maxEncryptedArchiveSize int64 = maxArchiveSize + (maxArchiveSize/encryptionChunkSize+1)*20 + encryptionHeaderSize + 20

func destinationKeyPath(dataDir, destinationID string) string {
	return filepath.Join(dataDir, "backup-keys", destinationID+".key")
}

func ensureDestinationKey(dataDir, destinationID string) ([]byte, bool, error) {
	if len(destinationID) < 16 || len(destinationID) > 64 || !hexString.MatchString(destinationID) {
		return nil, false, errors.New("backup destination id is invalid")
	}
	dir := filepath.Join(dataDir, "backup-keys")
	if err := securefile.MkdirAll(dir); err != nil {
		return nil, false, errors.New("backup recovery key directory is unavailable")
	}
	if err := securefile.CheckDirectory(dir); err != nil {
		return nil, false, errors.New("backup recovery key directory is not private")
	}
	path := destinationKeyPath(dataDir, destinationID)
	f, err := securefile.Create(path)
	if errors.Is(err, os.ErrExist) {
		key, readErr := readDestinationKey(path)
		return key, false, readErr
	}
	if err != nil {
		return nil, false, errors.New("backup recovery key could not be created")
	}
	key := make([]byte, RecoveryKeySize)
	if _, err := rand.Read(key); err != nil {
		f.Close()
		os.Remove(path)
		return nil, false, errors.New("backup recovery key could not be generated")
	}
	if _, err := f.Write(key); err != nil {
		f.Close()
		os.Remove(path)
		return nil, false, errors.New("backup recovery key could not be saved")
	}
	if err := f.Sync(); err != nil {
		f.Close()
		os.Remove(path)
		return nil, false, errors.New("backup recovery key could not be saved")
	}
	if err := f.Close(); err != nil {
		os.Remove(path)
		return nil, false, errors.New("backup recovery key could not be saved")
	}
	return key, true, nil
}

func readDestinationKey(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0 || info.Size() != RecoveryKeySize {
		return nil, errors.New("backup recovery key is unavailable")
	}
	if err := securefile.Check(path, info); err != nil {
		return nil, errors.New("backup recovery key is not private")
	}
	key, err := os.ReadFile(path)
	if err != nil || len(key) != RecoveryKeySize {
		return nil, errors.New("backup recovery key is unavailable")
	}
	return key, nil
}

// ExportDestinationRecoveryKey returns the printable key needed to recover files
// written for this destination. The key lives outside the archive and is never
// generated by an export request.
func ExportDestinationRecoveryKey(dataDir, destinationID string) (string, error) {
	if len(destinationID) < 16 || len(destinationID) > 64 || !hexString.MatchString(destinationID) {
		return "", errors.New("backup destination id is invalid")
	}
	key, err := readDestinationKey(destinationKeyPath(dataDir, destinationID))
	if err != nil {
		return "", err
	}
	return hex.EncodeToString(key), nil
}

func destinationRecoveryKeyAvailable(dataDir, destinationID string) bool {
	key, err := readDestinationKey(destinationKeyPath(dataDir, destinationID))
	for i := range key {
		key[i] = 0
	}
	return err == nil
}

func removeDestinationKey(dataDir, destinationID string) error {
	if len(destinationID) < 16 || len(destinationID) > 64 || !hexString.MatchString(destinationID) {
		return errors.New("backup destination id is invalid")
	}
	path := destinationKeyPath(dataDir, destinationID)
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil || !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0 {
		return errors.New("backup recovery key is invalid")
	}
	if err := securefile.Check(path, info); err != nil {
		return errors.New("backup recovery key is not private")
	}
	return os.Remove(path)
}

// ReadRecoveryKeyFile reads the lower-case hex key exported by the admin interface.
func ReadRecoveryKeyFile(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0 || info.Size() > RecoveryKeySize*2+2 {
		return nil, errors.New("recovery key file is invalid")
	}
	if err := securefile.Check(path, info); err != nil {
		return nil, errors.New("recovery key file is not private")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, errors.New("recovery key file cannot be read")
	}
	text := strings.TrimRight(string(data), "\r\n")
	if len(text) != RecoveryKeySize*2 {
		return nil, errors.New("recovery key file has an invalid format")
	}
	key, err := hex.DecodeString(text)
	if err != nil || len(key) != RecoveryKeySize {
		return nil, errors.New("recovery key file has an invalid format")
	}
	return key, nil
}

func deriveAEAD(key, salt []byte) (cipher.AEAD, error) {
	if len(key) != RecoveryKeySize || len(salt) != 16 {
		return nil, errors.New("backup encryption key or salt is invalid")
	}
	derived := make([]byte, RecoveryKeySize)
	if _, err := io.ReadFull(hkdf.New(sha256.New, key, salt, []byte("BookmarksSync backup archive encryption v1")), derived); err != nil {
		return nil, errors.New("backup encryption key derivation failed")
	}
	block, err := aes.NewCipher(derived)
	for i := range derived {
		derived[i] = 0
	}
	if err != nil {
		return nil, errors.New("backup encryption is unavailable")
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, errors.New("backup encryption is unavailable")
	}
	return aead, nil
}

func archiveSource(path string, limit int64) (*os.File, error) {
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() || info.Mode()&os.ModeSymlink != 0 || info.Size() <= 0 || info.Size() > limit {
		return nil, errors.New("backup archive file is invalid or too large")
	}
	f, err := os.Open(path)
	if err != nil {
		return nil, errors.New("backup archive file cannot be opened")
	}
	return f, nil
}

// IsEncryptedArchive checks the fixed format marker without reading archive data.
func IsEncryptedArchive(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	var marker [8]byte
	if _, err := io.ReadFull(f, marker[:]); err != nil {
		return false, nil
	}
	return bytes.Equal(marker[:], encryptionMagic[:]), nil
}

// EncryptArchive writes a bounded-memory, chunk-authenticated envelope and never
// replaces an existing output file. A final authenticated frame detects truncation.
func EncryptArchive(ctx context.Context, sourcePath, outputPath string, key []byte) error {
	source, err := archiveSource(sourcePath, maxArchiveSize)
	if err != nil {
		return err
	}
	defer source.Close()
	if len(key) != RecoveryKeySize {
		return errors.New("backup recovery key is invalid")
	}
	var header [encryptionHeaderSize]byte
	copy(header[:8], encryptionMagic[:])
	if _, err := rand.Read(header[8:]); err != nil {
		return errors.New("backup encryption could not be initialized")
	}
	aead, err := deriveAEAD(key, header[8:])
	if err != nil {
		return err
	}
	return writeEncrypted(ctx, source, outputPath, header, aead)
}

func writeEncrypted(ctx context.Context, source io.Reader, outputPath string, header [encryptionHeaderSize]byte, aead cipher.AEAD) error {
	out, err := securefile.Create(outputPath)
	if err != nil {
		return errors.New("encrypted backup output already exists or cannot be created")
	}
	complete := false
	defer func() {
		_ = out.Close()
		if !complete {
			_ = os.Remove(outputPath)
		}
	}()
	if err := writeAll(out, header[:]); err != nil {
		return errors.New("encrypted backup could not be written")
	}
	buf := make([]byte, encryptionChunkSize)
	var counter uint32
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		n, readErr := io.ReadFull(source, buf)
		if readErr != nil && !errors.Is(readErr, io.EOF) && !errors.Is(readErr, io.ErrUnexpectedEOF) {
			return errors.New("backup archive could not be read")
		}
		if n > 0 {
			if counter == ^uint32(0) {
				return errors.New("backup archive has too many encryption chunks")
			}
			counter++
			if err := writeEncryptedFrame(out, aead, header[:], counter, buf[:n]); err != nil {
				return err
			}
		}
		if errors.Is(readErr, io.EOF) || errors.Is(readErr, io.ErrUnexpectedEOF) {
			if counter == ^uint32(0) {
				return errors.New("backup archive has too many encryption chunks")
			}
			counter++
			if err := writeEncryptedFrame(out, aead, header[:], counter, nil); err != nil {
				return err
			}
			break
		}
	}
	if err := out.Sync(); err != nil {
		return errors.New("encrypted backup could not be synced")
	}
	if err := out.Close(); err != nil {
		return errors.New("encrypted backup could not be closed")
	}
	complete = true
	return nil
}

func writeEncryptedFrame(out io.Writer, aead cipher.AEAD, header []byte, counter uint32, plain []byte) error {
	var nonce [12]byte
	binary.BigEndian.PutUint32(nonce[8:], counter)
	var length [4]byte
	binary.BigEndian.PutUint32(length[:], uint32(len(plain)))
	aad := make([]byte, 0, len(header)+8)
	aad = append(aad, header...)
	aad = append(aad, length[:]...)
	var counterBytes [4]byte
	binary.BigEndian.PutUint32(counterBytes[:], counter)
	aad = append(aad, counterBytes[:]...)
	sealed := aead.Seal(nil, nonce[:], plain, aad)
	if err := writeAll(out, length[:]); err != nil {
		return errors.New("encrypted backup could not be written")
	}
	if err := writeAll(out, sealed); err != nil {
		return errors.New("encrypted backup could not be written")
	}
	return nil
}

// DecryptArchive authenticates every frame and publishes no partial plaintext file.
func DecryptArchive(ctx context.Context, sourcePath, outputPath string, key []byte) error {
	source, err := archiveSource(sourcePath, maxEncryptedArchiveSize)
	if err != nil {
		return err
	}
	defer source.Close()
	if len(key) != RecoveryKeySize {
		return errors.New("backup recovery key is invalid")
	}
	var header [encryptionHeaderSize]byte
	if _, err := io.ReadFull(source, header[:]); err != nil || !bytes.Equal(header[:8], encryptionMagic[:]) {
		return errors.New("encrypted backup header is invalid")
	}
	aead, err := deriveAEAD(key, header[8:])
	if err != nil {
		return err
	}
	out, err := securefile.Create(outputPath)
	if err != nil {
		return errors.New("decrypted backup output already exists or cannot be created")
	}
	complete := false
	defer func() {
		_ = out.Close()
		if !complete {
			_ = os.Remove(outputPath)
		}
	}()
	var counter uint32
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		var lengthBytes [4]byte
		if _, err := io.ReadFull(source, lengthBytes[:]); err != nil {
			return errors.New("encrypted backup is truncated")
		}
		length := binary.BigEndian.Uint32(lengthBytes[:])
		if length > encryptionChunkSize {
			return errors.New("encrypted backup frame is invalid")
		}
		if counter == ^uint32(0) {
			return errors.New("encrypted backup has too many frames")
		}
		counter++
		sealed := make([]byte, int(length)+aead.Overhead())
		if _, err := io.ReadFull(source, sealed); err != nil {
			return errors.New("encrypted backup is truncated")
		}
		var nonce [12]byte
		binary.BigEndian.PutUint32(nonce[8:], counter)
		aad := make([]byte, 0, len(header)+8)
		aad = append(aad, header[:]...)
		aad = append(aad, lengthBytes[:]...)
		var counterBytes [4]byte
		binary.BigEndian.PutUint32(counterBytes[:], counter)
		aad = append(aad, counterBytes[:]...)
		plain, err := aead.Open(nil, nonce[:], sealed, aad)
		if err != nil {
			return errors.New("encrypted backup authentication failed")
		}
		if length == 0 {
			var trailing [1]byte
			if n, err := source.Read(trailing[:]); n != 0 || !errors.Is(err, io.EOF) {
				return errors.New("encrypted backup has trailing data")
			}
			break
		}
		if err := writeAll(out, plain); err != nil {
			return errors.New("decrypted backup could not be written")
		}
	}
	if err := out.Sync(); err != nil {
		return errors.New("decrypted backup could not be synced")
	}
	if err := out.Close(); err != nil {
		return errors.New("decrypted backup could not be closed")
	}
	complete = true
	return nil
}

func writeAll(out io.Writer, value []byte) error {
	for len(value) > 0 {
		n, err := out.Write(value)
		if err != nil {
			return err
		}
		if n == 0 {
			return fmt.Errorf("%w", io.ErrShortWrite)
		}
		value = value[n:]
	}
	return nil
}
